const buildPatch = locale => {
  const data = localeData[locale];
  const patch = { ...data.shared };

  sports.forEach(sport => {
    patch[`CoachDirectory.heroTitle.${sport}`] = data.heroTitle[sport];
    patch[`CoachDirectory.heroSubtitle.${sport}`] = data.heroSubtitle[sport];
    patch[`CoachDirectory.schemaTitle.${sport}`] = data.schemaTitle[sport];
    patch[`CoachDirectory.schemaDescription.${sport}`] = data.schemaDescription[sport];
    patch[`CoachDirectory.heroBannerAriaLabel.${sport}`] = data.heroTitle[sport];
  });

  return patch;
};

['en', 'it', 'de', 'fr', 'es', 'pt'].forEach(locale => {
  const filePath = path.join(translationsDir, `${locale}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const patch = buildPatch(locale);
  let updated = 0;

  Object.entries(patch).forEach(([key, value]) => {
    data[key] = value;
    updated += 1;
  });

  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`);
  console.log(`Updated ${locale}.json (${updated} sport directory keys)`);
});
