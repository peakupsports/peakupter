const applyReplacements = (text, replacements) => {
  if (!text || typeof text !== 'string') {
    return text;
  }
  let out = text;
  replacements.forEach(([from, to]) => {
    out = out.split(from).join(to);
  });
  return out;
};

/** @param {string} text */
exports.frToIt = text => applyReplacements(text, FR_IT_REPLACEMENTS);

/** @param {string} text */
exports.esToPt = text => applyReplacements(text, ES_PT_REPLACEMENTS);
